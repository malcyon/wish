COLS = 40


def encode(ch):
    if ch == "@":
        return 0
    if "A" <= ch <= "Z":
        return ord(ch) - 64
    return ord(ch)


class FakeKeyboard:
    def __init__(self, game):
        self.game, self.sent = game, []

    def key(self, name, hold=0.0, gap=0.0):
        self.sent.append((self.game.state, name))
        self.game.key(name)

    def text(self, s, hold=0.0, gap=0.0):
        self.sent.append((self.game.state, "text " + s))
        self.game.typed += s.upper()

    def screenshot(self, path, **_kw):
        pathlib.Path(path).write_bytes(b"png")
        return True


class FakeGame:
    """The screens of CREATE NEW CHARACTER, ADD and SAVE, one state each."""

    PARTY_EMPTY = ["CREATE NEW CHARACTER", "ADD CHARACTER TO PARTY",
                   "LOAD SAVED GAME"]
    PARTY_FULL = ["CREATE NEW CHARACTER", "DROP CHARACTER", "MODIFY CHARACTER",
                  "VIEW CHARACTER", "ADD CHARACTER TO PARTY",
                  "REMOVE CHARACTER FROM PARTY", "SAVE CURRENT GAME",
                  "BEGIN ADVENTURING"]

    def __init__(self, tmp, rolls=ROLLS, add_closes=False, stall=None,
                 start="party", lose_first=None, slow=None, trim=()):
        """`stall`: a state whose keys do nothing.  `lose_first`: a state whose
        first Return is dropped.  `slow`: state -> (polls, redraws), a Return
        that is accepted but takes that many screen reads to show its result,
        the screen redrawn meanwhile or left as it was.  `trim`: class labels
        the roll does not qualify for, left off the class list."""
        self.trim = tuple(trim)
        self.tmp, self.rolls = tmp, list(rolls)
        self.add_closes, self.stall = add_closes, stall
        self.lose_first, self.slow = lose_first, dict(slow or {})
        self.delayed = None             # [polls left, state the key was sent in]
        self.camped = False
        self.state, self.cursor, self.typed = start, 0, ""
        self.rolled = 0
        self.roll = {}
        self.pick = {}
        self.created: list = []      # (spec-ish dict, roll) in memory
        self.added: list[str] = []
        self.on_disk_created: list = []
        self.saved = False
        self.saving_polls = 0
        self.chosen: list[tuple[str, str]] = []
        self.save_disk = str(tmp / "SIDE0.D64")
        D64.blank().save(self.save_disk)

    # -- what is on each screen ---------------------------------------------

    def items(self):
        s = self.state
        if s == "party":
            return self.PARTY_FULL if self.added else self.PARTY_EMPTY
        if s == "race":
            return list(creation.RACES) + ["EXIT"]
        if s == "gender":
            return list(creation.GENDERS)
        if s == "roll":
            return ["ROLL AGAIN", "KEEP"]
        if s == "class":
            return [c for c in CLASSES[self.pick["race"]] if c not in self.trim]
        if s == "align":
            aligns = list(creation.ALIGNMENTS)
            if "CLERIC" in self.pick["class"]:
                aligns.remove("TRUE NEUTRAL")
            if "THIEF" in self.pick["class"]:
                aligns = [a for a in aligns
                          if a not in ("LAWFUL GOOD", "CHAOTIC GOOD")]
            return aligns
        if s == "sheet":
            return ["YES", "NO"]
        if s == "add":
            return [c["name"] for c in self.created] + ["EXIT"]
        return []

    def render(self):
        codes = bytearray(0x20 for _ in range(25 * COLS))
        colours = bytearray(5 for _ in range(25 * COLS))

        def put(row, col, text, hot=False):
            for i, ch in enumerate(text):
                codes[row * COLS + col + i] = encode(ch)
                if hot:
                    colours[row * COLS + col + i] = 1

        s, items = self.state, self.items()

        def listing(prompt, col, first=2, whole_row=False):
            for i, label in enumerate(items):
                hot = i == self.cursor
                put(first + i, col, label, hot)
                if hot and whole_row:
                    for c in range(1, 39):
                        colours[(first + i) * COLS + c] = 1
            put(first + len(items) + 1, 2, prompt)

        if s == "party":
            for i, label in enumerate(items):
                put(13 + i, 2, label, i == self.cursor)
        elif s == "race":
            listing("PICK RACE", 2)
        elif s == "gender":
            listing("PICK GENDER", 2)
        elif s == "roll":
            put(5, 2, f"RACE {self.pick['race']}")
            for i, (k, v) in enumerate(self.roll.items()):
                put(6 + i, 2, f"{k.upper()} {v}")
            for i, label in enumerate(items):
                put(12 + i, 2, label, i == self.cursor)
        elif s == "class":
            listing("PICK CLASS", 1, whole_row=True)
        elif s == "align":
            listing("PICK ALIGNMENT", 2)
        elif s == "name":
            put(2, 2, "INPUT NAME OF CHARACTER")
            put(3, 2, self.typed.lower().upper())
        elif s == "sheet":
            put(13, 28, "SAVE?")
            for i, label in enumerate(items):
                put(15 + i, 28, label, i == self.cursor)
        elif s == "disk3":
            # Unmeasured: this prompt after a second character's sheet is a
            # guess from the loader's code.
            put(18, 2, "INSERT GAME DISK #3")
            put(24, 0, "PRESS ANY KEY TO CONTINUE")
        elif s in ("portrait", "icon", "save_yn"):
            bar = {"portrait": ["CHANGE:HEAD", "BODY", "KEEP"],
                   "icon": ["ICON:PARTS", "COLOR", "SIZE", "EXIT"],
                   "save_yn": ["SAVE GAME: YES", "NO"]}[s]
            col = 0
            for i, word in enumerate(bar):
                label = word.split(":")[-1].split(" ")[-1]
                put(24, col, word + " ")
                start = col + len(word) - len(label)
                if i == self.cursor:
                    put(24, start, label, True)
                col += len(word) + 1
        elif s == "diskprompt":
            put(24, 0, "INSERT YOUR SAVE GAME DISK")
        elif s == "add":
            for i, label in enumerate(items):
                star = "*" if label in self.added else " "
                put(2 + i, 3, star)
                put(2 + i, 4, label, i == self.cursor)
            put(2 + len(items) + 2, 2, "ADD CHARACTER TO PARTY")
        elif s == "saving":
            put(10, 2, "SAVING GAME")
            for i, label in enumerate(self.PARTY_FULL):
                put(13 + i, 2, label)
        elif s == "junk":
            put(5, 5, "A SCREEN NOBODY DRAWS")
        if self.delayed and self.slow[self.delayed[1]][1]:
            put(22, 5, "LOADING")     # the screen changes, not to the next one
        return Screen(bytes(codes), bytes(colours), 0x0400)

    def bar_words(self):
        return {"portrait": ["HEAD", "BODY", "KEEP"],
                "icon": ["PARTS", "COLOR", "SIZE", "EXIT"],
                "save_yn": ["YES", "NO"]}[self.state]

    # -- what a key does ----------------------------------------------------

    def new_roll(self):
        self.roll = dict(self.rolls[self.rolled % len(self.rolls)])
        self.rolled += 1

    def go(self, state):
        self.state, self.cursor = state, 0

    def key(self, name):
        if self.stall == self.state or self.delayed:
            return
        if name == "Return" and self.lose_first == self.state:
            self.lose_first = None
            return
        if name == "Return" and self.state in self.slow:
            self.delayed = [self.slow[self.state][0], self.state]
            return
        s = self.state
        if name in ("Down", "Right"):
            n = len(self.bar_words() if s in ("portrait", "icon", "save_yn")
                    else self.items())
            self.cursor = min(self.cursor + 1, n - 1)
        elif name in ("Up", "Left"):
            self.cursor = max(self.cursor - 1, 0)
        elif name == "space":
            if s == "diskprompt":
                self.write()
            elif s == "disk3":
                self.go("portrait")
        elif name == "Return":
            self.enter()

    def enter(self):
        s = self.state
        words = (self.bar_words() if s in ("portrait", "icon", "save_yn")
                 else self.items())
        label = words[self.cursor] if words else ""
        self.chosen.append((s, label))
        if s == "party":
            self.go({"CREATE NEW CHARACTER": "race",
                     "ADD CHARACTER TO PARTY": "add",
                     "SAVE CURRENT GAME": "save_yn",
                     "BEGIN ADVENTURING": "world"}[label])
        elif s == "race":
            if label == "EXIT":
                self.go("party")
            else:
                self.pick["race"] = label
                self.go("gender")
        elif s == "gender":
            self.pick["gender"] = label
            self.new_roll()
            self.go("roll")
        elif s == "roll":
            if label == "KEEP":
                self.go("class")
            else:
                self.new_roll()
        elif s == "class":
            self.pick["class"] = label
            self.go("align")
        elif s == "align":
            self.pick["alignment"] = label
            self.typed = ""
            self.go("name")
        elif s == "name":
            if self.typed:
                self.pick["name"] = self.typed
                self.go("sheet")
        elif s == "sheet":
            self.go("disk3" if self.created else "portrait")
        elif s == "portrait" and label == "KEEP":
            self.go("icon")
        elif s == "icon" and label == "EXIT":
            self.go("diskprompt")
        elif s == "add":
            if label == "EXIT":
                self.go("party")
            else:
                self.added.append(label)
                if self.add_closes and len(self.added) == len(self.created):
                    self.go("party")
        elif s == "save_yn":
            if label == "YES":
                self.saving_polls = 2
                self.go("saving")

    def back(self):
        s = self.state
        if s == "align":
            self.go("class")
        elif s == "class":
            self.new_roll()
            self.go("roll")
        elif s == "roll":
            self.go("gender")
        elif s == "gender":
            self.go("race")

    def write(self):
        self.created.append({**self.pick, "roll": dict(self.roll)})
        self.go("race")

    def tick(self):
        """One read of the screen: the write to the disk runs on."""
        if self.delayed:
            self.delayed[0] -= 1
            if self.delayed[0] <= 0:
                self.delayed = None
                self.enter()
        if self.state == "saving" and self.stall != "saving":
            self.saving_polls -= 1
            if self.saving_polls <= 0:
                self.saved = True
                self.go("party")
                self.cursor = 6

    def flush(self):
        """The drive shows its directory only once the head has moved."""
        records = []
        for c in self.created:
            sp = spec(c["name"], c["race"], c["gender"], c["class"],
                      c["alignment"])
            records.append(record(sp, c["roll"]))
        disk(records, party=self.saved, camp=self.camped).save(self.save_disk)


class FakeSession(S.Session):
    """A `Session` whose screen and keyboard are the scripted game."""

    def __init__(self, game):
        self.script = game
        self.kbd = FakeKeyboard(game)
        self.here = str(game.tmp)
        self.save_disk = game.save_disk
        self.attached = "SIDE1.D64"
        self.attaches: list[str] = []
        self.kernal: list[int] = []
        self.world_timeouts: list[float] = []
        self.camp_saves = 0
        self.camp_lands = True
        self.camp_wipes = False
        self.world_arrives = True

    def screen(self):
        self.script.tick()
        if self.script.state == "world":
            return None
        return self.script.render()

    def attach(self, path, unit=8, settle=None):
        self.attaches.append(pathlib.Path(path).name)
        if pathlib.Path(path) == pathlib.Path(self.script.save_disk):
            self.script.flush()

    def handle_prompt(self, s=None):
        want = self.wanted_disk(s if s is not None else self.screen())
        if want is None:
            return False
        self.attach(want)
        self.kbd.key("space")
        return True

    def press_kernal(self, code):
        self.kernal.append(code)
        if code == 0x5F:
            self.script.back()

    def wait_for_world(self, timeout=240.0, interval=0.35):
        self.world_timeouts.append(timeout)
        return self.world_arrives

    def save_game(self, to=None):
        self.camp_saves += 1
        self.script.camped = self.camp_lands
        self.script.flush()
        if self.camp_wipes:
            D64.blank().save(self.script.save_disk)
        return True


class Clock:
    def __init__(self):
        self.now = 0.0

    def __call__(self):
        return self.now

    def sleep(self, seconds):
        self.now += seconds


def drive(tmp, specs, game=None, **kw):
    game = game or FakeGame(tmp)
    sess = FakeSession(game)
    clock = Clock()
    out = tmp / "run"
    code = creation.run(sess, out, specs=specs, clock=clock,
                        sleep=clock.sleep, **kw)
    return code, sess, game, out, json.loads((out / "summary.json").read_text())


