def test_the_add_list_gets_exit_only_while_it_is_still_up(tmp_path):
    """The list stays up after the last add on the C64, so EXIT leaves it; a
    list that had closed itself is not pressed at."""
    code, _sess, game, _out, _s = drive(tmp_path, PAIR)
    assert code == 0
    assert [lab for st, lab in game.chosen if st == "add"] \
        == ["VICEFTR", "VICEDWF", "EXIT"]

    code, _sess, closing, _out, _s = drive(
        tmp_path / "closing", PAIR,
        FakeGame(_mkdir(tmp_path / "closing"), add_closes=True))
    assert code == 0
    assert [lab for st, lab in closing.chosen if st == "add"] \
        == ["VICEFTR", "VICEDWF"]
    assert ("party", "EXIT") not in closing.chosen


