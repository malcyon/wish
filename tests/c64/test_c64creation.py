def test_a_deadline_passing_mid_step_writes_lost_to_the_summary(tmp_path):
    """The write never finishes: the run stops at its own deadline, keeps the
    screen it was looking at, and says so in `summary.json`."""
    game = FakeGame(tmp_path, stall="saving")
    sess = FakeSession(game)
    clock = Clock()
    out = tmp_path / "run"
    code = creation.run(sess, out, specs=PAIR[:1], max_seconds=200.0,
                        clock=clock, sleep=clock.sleep)
    summary = json.loads((out / "summary.json").read_text())
    assert code == 1 and summary["completed"] is False
    assert "seconds were spent" in summary["lost"]
    assert clock.now < 200.0     # ended inside the cleanup window, not past it
    assert list((out / "shots").glob("*lost-deadline.txt"))


