def spec(name="VICEFTR", race="HUMAN", gender="MALE", cls="FIGHTER",
         alignment="LAWFUL GOOD"):
    return creation.Spec.from_json({"name": name, "race": race,
                                    "gender": gender, "class": cls,
                                    "alignment": alignment})


def record(sp, roll, exceptional=0):
    """What the engine would have written for SP, generated by `testparty`."""
    one = testparty.build(testparty.Spec(
        name=sp.name, race=creation.RACES[sp.race],
        sex=creation.GENDERS[sp.gender], levels=dict(sp.classes),
        abilities=dict(roll), alignment=creation.ALIGNMENTS.index(sp.alignment),
        age=20, experience=0, portrait=(0, 1)))
    if exceptional:
        one.record.set("exceptional_strength", exceptional)
    return one.record


def disk(records, party=False, exports=True, names=None, camp=False):
    """A save disk: the `\\x01NAME` exports, and SAVEDGAME0 once saved.
    `names` are the file names when they differ from the records' own; `camp`
    makes the SAVEDGAME0 differ from a party-menu save's."""
    image = D64.blank()
    if exports:
        for rec, name in zip(records, names or [r.name for r in records]):
            image.write_file(b"\x01" + name.encode(), rec.to_prg())
    if party:
        sg0 = savegame.SaveGame0(bytes(GAME.save_size), GAME)
        for i, rec in enumerate(records):
            sg0.write_record(i, rec)
        prg = bytearray(sg0.to_prg())
        if camp:
            prg[-1] ^= 1
        image.write_file(b"SAVEDGAME0", bytes(prg))
    return image


def write_disks(tmp, records, names=None):
    """The two disks a build leaves: exports before the add, slots after."""
    disk(records, names=names).save(str(tmp / "rolled.D64"))
    disk(records, party=True, exports=False).save(str(tmp / "party.D64"))


