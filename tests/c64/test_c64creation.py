def test_every_spec_entry_is_selected_by_its_label(tmp_path):
    """Each character's race, gender, class and alignment are taken by name
    off their own lists, the roll is kept by moving to KEEP rather than by
    pressing Return on the screen's first row, and the records read back match.
    """
    code, sess, game, out, summary = drive(tmp_path, PAIR)
    assert summary["lost"] is None and summary["completed"] is True and code == 0
    picked = [(s, lab) for s, lab in game.chosen if s not in ("party", "name")]
    assert picked[:6] == [("race", "HUMAN"), ("gender", "MALE"),
                          ("roll", "KEEP"), ("class", "FIGHTER"),
                          ("align", "LAWFUL GOOD"), ("sheet", "YES")]
    assert ("race", "DWARF") in picked and ("gender", "FEMALE") in picked
    assert ("class", "FIGHTER/THIEF") in picked
    assert ("align", "LAWFUL NEUTRAL") in picked
    assert ("roll", "ROLL AGAIN") not in picked
    assert (out / "records.txt").read_text().splitlines()[-1] \
        == "all records match the spec"
    assert {p.name for p in out.glob("*.D64")} >= {"rolled.D64", "party.D64"}
    assert list((out / "shots").glob("*.txt"))
    lines = [json.loads(ln) for ln in (out / "run.jsonl").read_text().splitlines()]
    assert [ln["strength"] for ln in lines if ln["kind"] == "roll"] == [17, 12]


def test_the_save_disk_is_reattached_before_each_copy(tmp_path):
    """The drive shows its directory only after the head moves, so a copy
    taken without a re-attach holds no characters: both disks must name them."""
    code, sess, game, out, summary = drive(tmp_path, PAIR)
    assert code == 0
    assert sess.attaches.count("SIDE0.D64") >= 2
    exports = D64.open(str(out / "rolled.D64"))
    for name in (b"\x01VICEFTR", b"\x01VICEDWF"):
        assert len(exports.read_file(name)) == 582


def test_a_class_the_race_is_never_offered_is_refused_before_any_key(tmp_path):
    """No magic-user in a dwarf's class list: the refusal comes before the
    first character is created, even when the dwarf is the second spec."""
    dwarf = spec("VICEMAG", "DWARF", "MALE", "MAGIC-USER", "LAWFUL GOOD")
    code, sess, game, out, summary = drive(tmp_path, [PAIR[0], dwarf])
    assert code == 1 and "a DWARF is never offered MAGIC-USER" in summary["lost"]
    assert sess.kbd.sent == [] and sess.kernal == [] and sess.attaches == []


