def test_a_stop_before_the_run_still_leaves_a_summary(tmp_path, monkeypatch):
    """Staging raises before `run` is reached; `main` still writes one."""
    class Slot:
        dir = str(tmp_path / "slot")

        def teardown(self):
            pass

        def release(self):
            pass

    out = tmp_path / "evidence"
    monkeypatch.setattr(creation.S, "claim_slot", lambda *a, **k: Slot())

    def boom(*_a, **_k):
        raise RuntimeError("no disks to stage")
    monkeypatch.setattr(creation.S, "stage_disks", boom)
    monkeypatch.setattr(creation.evidence, "default_out", lambda *a, **k: out)
    monkeypatch.setattr(creation.runlog, "catch_signals", lambda: None)
    with pytest.raises(RuntimeError):
        creation.main(["--lists", "--issue", "1", "--run", "r",
                       "--disks", str(tmp_path)])
    summary = json.loads((out / "summary.json").read_text())
    assert summary["completed"] is False and "no disks to stage" in summary["lost"]


class Slot:
    def __init__(self, tmp):
        self.dir = str(tmp / "slot")
        self.calls = []

    def teardown(self):
        self.calls.append("teardown")

    def release(self):
        self.calls.append("release")


