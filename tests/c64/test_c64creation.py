def checked(tmp_path, mutate=None, exceptional=0):
    sp = PAIR[0]
    rec = record(sp, ROLLS[0], exceptional)
    if mutate:
        mutate(rec)
    write_disks(tmp_path, [rec], names=[sp.name])
    return creation.check_records(tmp_path / "rolled.D64",
                                  tmp_path / "party.D64", [sp],
                                  {"VICEFTR": ROLLS[0]})


def test_matching_records_pass(tmp_path):
    assert checked(tmp_path)[-1] == "all records match the spec"


