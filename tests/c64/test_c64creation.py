def checked(tmp_path, mutate=None, where="both", exceptional=0):
    """The records check on one character; MUTATE alters the record on the
    export, the slot or both, so each side is proved to be compared."""
    sp = PAIR[0]
    exported, slotted = (record(sp, ROLLS[0], exceptional) for _ in range(2))
    if mutate:
        if where in ("export", "both"):
            mutate(exported)
        if where in ("party", "both"):
            mutate(slotted)
    disk([exported], names=[sp.name]).save(str(tmp_path / "rolled.D64"))
    disk([slotted], party=True, exports=False).save(str(tmp_path / "party.D64"))
    return creation.check_records(tmp_path / "rolled.D64",
                                  tmp_path / "party.D64", [sp],
                                  {"VICEFTR": ROLLS[0]})


