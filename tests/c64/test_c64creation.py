"""`tools/c64/creation.py` against a scripted game: no emulator, no display.

The fake is a small state machine of the creation screens of C64 Pool of
Radiance -- the roll before the class, the ADD list that stays up, the drive
that only shows its directory after a re-attach -- and the driver under test is
the real one, calling the real `Session.select_row` and `Session.select_bar`
against it.  Its `disk3` screen is a guess, not a measured one.  Records are generated by
`tools/suite/testparty.py`, never read from game data.
"""

